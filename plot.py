"""Plot GEMM/GEMV/Conv2D throughput (or latency) and paired-baseline speedups."""

import argparse
import csv
import hashlib
import json
import math
from pathlib import Path
from typing import Any

OPS = ("gemm", "gemv", "conv2d")
ORDER = ("pytorch", "tvm", "iree", "openblas", "mimir")
NAMES = dict(
    pytorch="PyTorch", tvm="TVM", iree="IREE", openblas="OpenBLAS", mimir="MimIR"
)
COLORS = dict(
    pytorch="#64748b",
    tvm="#2563eb",
    iree="#d97706",
    openblas="#059669",
    mimir="#9333ea",
)


def read_rows(path):
    with path.open(newline="") as handle:
        reader = csv.DictReader(handle)
        required = {
            "backend",
            "op",
            "name",
            "shape",
            "median_ms",
            "gflops",
            "baseline_backend",
            "baseline_ms",
            "speedup",
        }
        if not required.issubset(reader.fieldnames or []):
            raise ValueError("Expected the long-form summary.csv generated by run.py")
        rows = []
        seen = set()
        shapes = {}
        for line, source in enumerate(reader, 2):
            row: dict[str, Any] = dict(source)
            row["op"] = "conv2d" if row["op"] == "conv" else row["op"]
            if row["op"] not in OPS:
                raise ValueError(f"Line {line}: unknown operator {row['op']}")
            row["shape"] = json.loads(row["shape"])
            dims = row["shape"]
            count = {"gemm": 3, "gemv": 2, "conv2d": 9}[row["op"]]
            if (
                not isinstance(dims, list)
                or len(dims) != count
                or any(type(d) is not int for d in dims)
            ):
                raise ValueError(f"Line {line}: invalid operator dimensions")
            if (
                row.get("cpu")
                and row.get("baseline_cpu")
                and row["cpu"] != row["baseline_cpu"]
            ):
                raise ValueError(
                    f"Line {line}: backend and paired baseline use different CPUs"
                )
            case = (row["op"], row["name"])
            if case in shapes and shapes[case] != row["shape"]:
                raise ValueError(f"Line {line}: same case name has different shapes")
            shapes[case] = row["shape"]
            row["series"] = (
                row["backend"],
                row.get("variant", "default"),
                row.get("cpu", ""),
            )
            key = (row["series"], *case)
            if key in seen:
                raise ValueError(f"Line {line}: duplicate result for {key}")
            seen.add(key)
            for field in ("median_ms", "gflops", "baseline_ms", "speedup"):
                row[field] = float(row[field])
                if not math.isfinite(row[field]) or row[field] <= 0:
                    raise ValueError(
                        f"Line {line}: {field} must be finite and positive"
                    )
            expected = row["baseline_ms"] / row["median_ms"]
            if not math.isclose(row["speedup"], expected, rel_tol=1e-6):
                raise ValueError(f"Line {line}: inconsistent paired-baseline speedup")
            rows.append(row)
    if not rows:
        raise ValueError("Input contains no benchmark results")
    return rows


def label(series):
    backend, variant, cpu = series
    details = [variant.replace("_", " ")] if variant and variant != "default" else []
    if cpu:
        details.append("CPU " + cpu)
    return NAMES.get(backend, backend) + (
        " (" + ", ".join(details) + ")" if details else ""
    )


def case_label(row, show_shapes):
    if not show_shapes:
        return row["name"]
    dims = row["shape"]
    if row["op"] == "gemm":
        m, n, k = dims
        shape = f"{m}×{k}×{n}"  # File convention: M,K,N.
    elif row["op"] == "gemv":
        shape = "×".join(map(str, dims))
    else:
        n, ci, h, w, co, kh, kw, stride, pad = dims
        shape = f"N{n} C{ci} {h}×{w}\nO{co} K{kh}×{kw} s{stride} p{pad}"
    return row["name"] + "\n" + shape


def plot(
    rows,
    ops,
    out,
    absolute="gflops",
    scale="log",
    formats=("png", "svg"),
    dpi=180,
    show_shapes=True,
):
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from matplotlib.patches import Patch
    import numpy as np

    series = sorted(
        {r["series"] for r in rows},
        key=lambda s: (ORDER.index(s[0]) if s[0] in ORDER else len(ORDER), s),
    )
    baselines = {r["baseline_backend"] for r in rows}
    if len(baselines) != 1:
        raise ValueError("Input mixes baseline backends; plot these runs separately")
    baseline = NAMES.get(next(iter(baselines)), next(iter(baselines)))
    groups = {op: [r for r in rows if r["op"] == op] for op in ops}
    ops = [op for op in ops if groups[op]]
    if not ops:
        raise ValueError("No results match the selected operators/backends")
    max_cases = max(len({r["name"] for r in groups[op]}) for op in ops)
    width = max(17, max_cases * 0.8 + 7)
    files = []
    speedups = [r["speedup"] for r in rows]
    speed_limits = (min(min(speedups), 1) * 0.65, max(max(speedups), 1) * 1.65)

    def color(key, index):
        if key[0] == "pytorch" and key[1].startswith("inductor"):
            return "#dc2626"
        return COLORS.get(key[0], plt.get_cmap("tab10")(index % 10))

    def draw(axes, op):
        subset = groups[op]
        cases = list(dict.fromkeys(r["name"] for r in subset))
        lookup = {(r["series"], r["name"]): r for r in subset}
        labels = [
            case_label(next(r for r in subset if r["name"] == name), show_shapes)
            for name in cases
        ]
        x = np.arange(len(cases))
        bar_width = 0.84 / len(series)
        for column, metric in enumerate(
            ("gflops" if absolute == "gflops" else "median_ms", "speedup")
        ):
            ax = axes[column]
            for index, key in enumerate(series):
                values = [
                    lookup[(key, name)][metric] if (key, name) in lookup else np.nan
                    for name in cases
                ]
                ax.bar(
                    x + (index - (len(series) - 1) / 2) * bar_width,
                    values,
                    width=bar_width,
                    color=color(key, index),
                    edgecolor="white",
                    linewidth=0.35,
                )
            ax.set_xticks(x, labels, rotation=35, ha="right", fontsize=8)
            ax.set_yscale(scale)
            ax.grid(axis="y", which="major", alpha=0.22)
            ax.set_axisbelow(True)
            ax.margins(x=0.01)
            title = op.upper() if op != "conv2d" else "Conv2D"
            if metric == "speedup":
                ax.axhline(1, color="#111827", linestyle="--", linewidth=1)
                ax.set_ylim(speed_limits if scale == "log" else (0, speed_limits[1]))
                ax.set_ylabel(f"Paired {baseline} / backend (×)")
                ax.set_title(title + " · Speedup (higher is better)")
            else:
                is_flops = metric == "gflops"
                ax.set_ylabel("GFLOP/s" if is_flops else "Latency (ms)")
                ax.set_title(
                    title
                    + (
                        " · Throughput (higher is better)"
                        if is_flops
                        else " · Latency (lower is better)"
                    )
                )
            ax.set_xlabel("Case / dimensions" if show_shapes else "Case")

    def render(selected, stem):
        with plt.rc_context(
            {
                "font.size": 10,
                "axes.spines.top": False,
                "axes.spines.right": False,
                "axes.titleweight": "bold",
                "svg.fonttype": "none",
                "pdf.fonttype": 42,
            }
        ):
            fig, axes = plt.subplots(
                len(selected),
                2,
                figsize=(width, 5 * len(selected) + 1.5),
                squeeze=False,
            )
            for index, op in enumerate(selected):
                draw(axes[index], op)
            fig.suptitle(
                "CPU operator benchmarks · absolute performance and speedup",
                fontsize=17,
                y=0.99,
            )
            handles = [
                Patch(facecolor=color(key, index), label=label(key))
                for index, key in enumerate(series)
            ]
            fig.legend(
                handles=handles,
                loc="upper center",
                bbox_to_anchor=(0.5, 0.966),
                ncol=min(len(series), 3),
                frameon=False,
                fontsize=9,
            )
            fig.text(
                0.02,
                0.012,
                f"Speedups use each backend's paired same-core {baseline} baseline; dashed line = 1×.\n"
                "Absolute bars use each runner's own CPU. GEMM dimensions: M×K×N; GEMV: M×K; Conv2D: NCHW/OIHW. Missing results are omitted.",
                fontsize=9,
                color="#475569",
            )
            fig.tight_layout(
                rect=(0, 0.06, 1, 0.91 if len(selected) == 1 else 0.945),
                h_pad=3,
                w_pad=2,
            )
            for fmt in formats:
                path = out / (stem + "." + fmt)
                fig.savefig(path, dpi=dpi, bbox_inches="tight", facecolor="white")
                files.append(str(path))
            plt.close(fig)

    out.mkdir(parents=True, exist_ok=True)
    render(ops, "overview_" + absolute)
    if len(ops) > 1:
        for op in ops:
            render([op], op + "_" + absolute)
    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "input",
        type=Path,
        help="summary.csv or a benchmark output directory containing it",
    )
    parser.add_argument("--output", type=Path, help="Default: <input directory>/plots")
    parser.add_argument("--absolute", choices=["gflops", "latency"], default="gflops")
    parser.add_argument("--scale", choices=["log", "linear"], default="log")
    parser.add_argument(
        "--ops",
        default="gemm,gemv,conv2d",
        help="Comma-separated operators; conv is an alias for conv2d",
    )
    parser.add_argument("--backends", help="Optional comma-separated backend filter")
    parser.add_argument(
        "--formats", default="png,svg", help="Comma-separated png,svg,pdf"
    )
    parser.add_argument("--dpi", type=int, default=180)
    parser.add_argument("--shapes", action=argparse.BooleanOptionalAction, default=True)
    args = parser.parse_args()
    source = args.input / "summary.csv" if args.input.is_dir() else args.input
    ops = ["conv2d" if op == "conv" else op for op in args.ops.split(",")]
    formats = args.formats.split(",")
    if len(set(ops)) != len(ops) or any(op not in OPS for op in ops):
        parser.error("--ops accepts gemm,gemv,conv2d (or conv)")
    if any(fmt not in ("png", "svg", "pdf") for fmt in formats) or args.dpi < 1:
        parser.error("Invalid formats or dpi")
    try:
        rows = read_rows(source)
        if args.backends:
            selected = set(args.backends.split(","))
            known = {r["backend"] for r in rows}
            if selected - known:
                raise ValueError(
                    f"Backends absent from input: {sorted(selected - known)}"
                )
            rows = [r for r in rows if r["backend"] in selected]
        rows = [r for r in rows if r["op"] in ops]
        out = args.output or source.parent / "plots"
        files = plot(
            rows, ops, out, args.absolute, args.scale, formats, args.dpi, args.shapes
        )
        provenance = dict(
            input=str(source.resolve()),
            input_sha256=hashlib.sha256(source.read_bytes()).hexdigest(),
            absolute=args.absolute,
            scale=args.scale,
            ops=ops,
            rows=len(rows),
            files=files,
        )
        (out / ("plot_" + args.absolute + ".json")).write_text(
            json.dumps(provenance, indent=2)
        )
    except (OSError, ValueError, KeyError) as exc:
        parser.error(str(exc))
    for path in files:
        print(path)


if __name__ == "__main__":
    main()
